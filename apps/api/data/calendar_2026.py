def get_active_calendar():
    """Return only active races (excluding cancelled)."""
    return [race for race in CALENDAR_2026 if race['status'] != 'cancelled']

def get_race_by_id(race_id):
    """Get race by ID."""
    for race in CALENDAR_2026:
        if race['id'] == race_id:
            return race
    return None

def get_race_by_round(round_number):
    """Get race by round number."""
    for race in CALENDAR_2026:
        if race['round'] == round_number:
            return race
    return None

def get_upcoming_races():
    """Return upcoming races."""
    return [race for race in CALENDAR_2026 if race['status'] == 'upcoming']

def get_completed_races():
    """Return completed races."""
    return [race for race in CALENDAR_2026 if race['status'] == 'completed']

def get_sprint_races():
    """Return sprint races."""
    return [race for race in CALENDAR_2026 if race.get('sprint', False)]

def get_total_rounds():
    """Return total number of rounds (excluding cancelled)."""
    return len(get_active_calendar())

def get_next_race():
    """Return the next upcoming race."""
    upcoming = get_upcoming_races()
    return upcoming[0] if upcoming else None

def get_circuit_names():
    """Return list of circuit names."""
    return [race['circuit'] for race in CALENDAR_2026]
