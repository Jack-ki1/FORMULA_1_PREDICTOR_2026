def get_driver_bio(driver_code):
    """Get driver biography by code."""
    return get_driver_bios().get(driver_code.upper())

def get_enhanced_driver_data(driver_code):
    """Combine roster data with biography."""
    driver = get_driver_by_code(driver_code)
    bio = get_driver_bio(driver_code)
    
    if driver and bio:
        return {**driver, **bio}
    elif driver:
        return driver
    return None

def get_all_enhanced_drivers():
    """Return all drivers with enhanced biographical data."""
    drivers = get_all_drivers()
    enhanced = []
    for driver in drivers:
        bio = get_driver_bio(driver['code'])
        if bio:
            enhanced.append({**driver, **bio})
        else:
            enhanced.append(driver)
    return enhanced
