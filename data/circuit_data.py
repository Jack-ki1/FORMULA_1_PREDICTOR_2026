def get_circuit_by_name(circuit_name):
    """Get circuit by name (partial match)."""
    circuit_name_lower = circuit_name.lower()
    for circuit_id, circuit_data in CIRCUITS.items():
        if circuit_name_lower in circuit_data['name'].lower():
            return circuit_data
    return None

def get_circuit_by_id(circuit_id):
    """Get circuit by ID."""
    return CIRCUITS.get(circuit_id.lower())

def get_all_circuits():
    """Return all circuits."""
    return list(CIRCUITS.values())

def get_circuit_characteristics(circuit_id):
    """Get circuit characteristics for prediction models."""
    circuit = get_circuit_by_id(circuit_id)
    if not circuit:
        return None
    
    return {
        'overtaking_difficulty': {'Low': 1.0, 'Medium': 0.6, 'High': 0.3}[circuit['overtaking']],
        'drs_zones_count': circuit['drs_zones'],
        'average_speed': circuit['avg_speed'],
        'full_throttle_percentage': circuit['full_throttle'],
        'corner_count': circuit['corners'],
        'safety_car_probability': circuit['safety_car_prob'],
        'rain_probability': circuit['rain_prob'],
        'base_temperature': circuit['base_temp'],
    }

def get_circuit_type(circuit_id):
    """Get circuit type (Permanent, Street, Semi-permanent)."""
    circuit = get_circuit_by_id(circuit_id)
    return circuit['type'] if circuit else 'Unknown'
